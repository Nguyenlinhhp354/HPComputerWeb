/* 06. Confirm stock documents. Call outside an existing transaction.
   All writers of document details must lock the parent row first and check DRAFT. */
DELIMITER $$
CREATE PROCEDURE sp_XacNhanPhieuNhapKho(IN p_MaPhieu VARCHAR(30))
BEGIN
    DECLARE v_TrangThai VARCHAR(20) DEFAULT NULL;
    DECLARE v_SoDong INT DEFAULT 0;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;
    START TRANSACTION;
    SELECT TrangThai INTO v_TrangThai FROM PhieuNhapKho
      WHERE MaPhieuNhap=p_MaPhieu FOR UPDATE;
    IF v_TrangThai IS NULL OR v_TrangThai <> 'DRAFT' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Phieu khong ton tai hoac khong o trang thai DRAFT.';
    END IF;
    SELECT COUNT(*) INTO v_SoDong FROM ChiTietPhieuNhapKho WHERE MaPhieuNhap=p_MaPhieu;
    IF v_SoDong = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Phieu phai co it nhat mot dong san pham.';
    END IF;
    UPDATE SanPham AS sp
    JOIN ChiTietPhieuNhapKho AS ct ON ct.MaSP=sp.MaSP
    SET sp.SoLuongTon=sp.SoLuongTon+ct.SoLuong
    WHERE ct.MaPhieuNhap=p_MaPhieu;
    IF ROW_COUNT() <> v_SoDong THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Khong the cap nhat day du ton kho; kiem tra so luong.';
    END IF;
    UPDATE PhieuNhapKho SET TrangThai='CONFIRMED' WHERE MaPhieuNhap=p_MaPhieu;
    COMMIT;
END$$

CREATE PROCEDURE sp_XacNhanPhieuXuatKho(IN p_MaPhieu VARCHAR(30))
BEGIN
    DECLARE v_TrangThai VARCHAR(20) DEFAULT NULL;
    DECLARE v_SoDong INT DEFAULT 0;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;
    START TRANSACTION;
    SELECT TrangThai INTO v_TrangThai FROM PhieuXuatKho
      WHERE MaPhieuXuat=p_MaPhieu FOR UPDATE;
    IF v_TrangThai IS NULL OR v_TrangThai <> 'DRAFT' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Phieu khong ton tai hoac khong o trang thai DRAFT.';
    END IF;
    SELECT COUNT(*) INTO v_SoDong FROM ChiTietPhieuXuatKho WHERE MaPhieuXuat=p_MaPhieu;
    IF v_SoDong = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Phieu phai co it nhat mot dong san pham.';
    END IF;
    UPDATE SanPham AS sp
    JOIN ChiTietPhieuXuatKho AS ct ON ct.MaSP=sp.MaSP
    SET sp.SoLuongTon=sp.SoLuongTon-ct.SoLuong
    WHERE ct.MaPhieuXuat=p_MaPhieu AND sp.SoLuongTon>=ct.SoLuong;
    IF ROW_COUNT() <> v_SoDong THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Khong the cap nhat day du ton kho; kiem tra so luong.';
    END IF;
    UPDATE PhieuXuatKho SET TrangThai='CONFIRMED' WHERE MaPhieuXuat=p_MaPhieu;
    COMMIT;
END$$


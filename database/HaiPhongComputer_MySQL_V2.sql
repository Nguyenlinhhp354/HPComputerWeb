CREATE TABLE TaiKhoan (
    MaTaiKhoan VARCHAR(30) PRIMARY KEY,
    TenDangNhap VARCHAR(80) NOT NULL UNIQUE,
    Email VARCHAR(254) NULL,
    MatKhauHash VARCHAR(255) NOT NULL,
    MaVaiTro VARCHAR(30) NOT NULL,
    MaNV VARCHAR(30) NULL,
    MaKH VARCHAR(30) NULL,
    TrangThai VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_TK_VaiTro FOREIGN KEY(MaVaiTro) REFERENCES VaiTro(MaVaiTro),
    CONSTRAINT FK_TK_NV FOREIGN KEY(MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT FK_TK_KH FOREIGN KEY(MaKH) REFERENCES KhachHang(MaKH),
    CONSTRAINT CK_TK_Owner CHECK ((CASE WHEN MaNV IS NULL THEN 0 ELSE 1 END + CASE WHEN MaKH IS NULL THEN 0 ELSE 1 END)=1),
    CONSTRAINT CK_TK_TrangThai CHECK (TrangThai IN ('ACTIVE','LOCKED','DISABLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE UNIQUE INDEX UX_TK_NV ON TaiKhoan(MaNV);
CREATE UNIQUE INDEX UX_TK_KH ON TaiKhoan(MaKH);
CREATE UNIQUE INDEX UX_TK_Email ON TaiKhoan(Email);

CREATE TABLE DonViTinh (
    MaDVT VARCHAR(30) PRIMARY KEY,

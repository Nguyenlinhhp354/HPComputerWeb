-- Target: MySQL 8.0.16+ or MariaDB 10.5+; InnoDB, UTF-8.
-- Create/select an EMPTY database in phpMyAdmin before importing.
-- No DROP, CREATE DATABASE or USE; existing databases are not removed.
-- All identifiers VARCHAR(30), supplied by backend (e.g. NV001).
-- Backend must authorize operations and prevent changes to confirmed stock documents.
SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

/* 01. Reference and identity tables */
CREATE TABLE NhaCungCap (
    MaNCC VARCHAR(30) PRIMARY KEY,
    TenNCC VARCHAR(200) NOT NULL,
    DiaChi VARCHAR(300) NULL,
    SoDienThoai VARCHAR(20) NULL,
    Email VARCHAR(254) NULL,
    TrangThai TINYINT(1) NOT NULL DEFAULT 1 CHECK (TrangThai IN (0,1)),
    CONSTRAINT UQ_NCC_Ten UNIQUE (TenNCC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE NhanVien (
    MaNV VARCHAR(30) PRIMARY KEY,
    TenNV VARCHAR(150) NOT NULL,
    ChucVu VARCHAR(100) NULL,
    DiaChi VARCHAR(300) NULL,
    Email VARCHAR(254) NULL,
    SoDienThoai VARCHAR(20) NULL,
    TrangThai TINYINT(1) NOT NULL DEFAULT 1 CHECK (TrangThai IN (0,1)),
    NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE UNIQUE INDEX UX_NhanVien_Email ON NhanVien(Email);

CREATE TABLE KhachHang (
    MaKH VARCHAR(30) PRIMARY KEY,
    TenKH VARCHAR(150) NOT NULL,
    Email VARCHAR(254) NULL,
    SoDienThoai VARCHAR(20) NULL,
    DiaChi VARCHAR(300) NULL,
    NgaySinh DATE NULL,
    GioiTinh VARCHAR(20) NULL,
    NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_KH_GioiTinh CHECK (GioiTinh IS NULL OR GioiTinh IN ('Nam','Nữ','Khác'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE UNIQUE INDEX UX_KhachHang_Email ON KhachHang(Email);

CREATE TABLE VaiTro (
    MaVaiTro VARCHAR(30) PRIMARY KEY,
    TenVaiTro VARCHAR(40) NOT NULL UNIQUE,
    MoTa VARCHAR(200) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


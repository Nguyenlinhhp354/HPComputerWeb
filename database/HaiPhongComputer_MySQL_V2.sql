/* 03. Promotions, shopping cart, sales */
CREATE TABLE KhuyenMai (
    MaKhuyenMai VARCHAR(30) PRIMARY KEY,
    TenKhuyenMai VARCHAR(200) NOT NULL,
    MaCode VARCHAR(40) NULL,
    KieuGiam VARCHAR(10) NOT NULL,

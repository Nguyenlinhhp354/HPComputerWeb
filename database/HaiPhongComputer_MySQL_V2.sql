CREATE TABLE DanhMuc (
    MaDanhMuc VARCHAR(30) PRIMARY KEY,
    TenDanhMuc VARCHAR(150) NOT NULL,
    MaDanhMucCha VARCHAR(30) NULL,
    TrangThai TINYINT(1) NOT NULL DEFAULT 1 CHECK (TrangThai IN (0,1)),
    CONSTRAINT FK_DM_Cha FOREIGN KEY(MaDanhMucCha) REFERENCES DanhMuc(MaDanhMuc),
    CONSTRAINT CK_DM_KhongTuThamChieu CHECK (MaDanhMucCha IS NULL OR MaDanhMucCha <> MaDanhMuc)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE LoaiSanPham (
    MaLoaiSP VARCHAR(30) PRIMARY KEY,
    TenLoaiSP VARCHAR(150) NOT NULL,
    MaDanhMuc VARCHAR(30) NOT NULL,
    CONSTRAINT FK_LSP_DM FOREIGN KEY(MaDanhMuc) REFERENCES DanhMuc(MaDanhMuc),
    CONSTRAINT UQ_LSP_DM_Ten UNIQUE (MaDanhMuc,TenLoaiSP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE SanPham (
    MaSP VARCHAR(30) PRIMARY KEY,
    TenSP VARCHAR(250) NOT NULL,
    MaLoaiSP VARCHAR(30) NOT NULL,
    MaDVT VARCHAR(30) NOT NULL,
    HangSanXuat VARCHAR(120) NULL,
    HinhAnhURL VARCHAR(500) NULL,
    ThongSoKyThuat LONGTEXT NULL,
    MoTa LONGTEXT NULL,
    GhiChu VARCHAR(500) NULL,
    GiaBan DECIMAL(18,2) NOT NULL,
    SoLuongTon INT NOT NULL DEFAULT 0,
    ThoiGianBaoHanhThang SMALLINT NOT NULL DEFAULT 0,
    TrangThai VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_SP_Loai FOREIGN KEY(MaLoaiSP) REFERENCES LoaiSanPham(MaLoaiSP),
    CONSTRAINT FK_SP_DVT FOREIGN KEY(MaDVT) REFERENCES DonViTinh(MaDVT),
    CONSTRAINT CK_SP_Gia CHECK (GiaBan >= 0),
    CONSTRAINT CK_SP_Ton CHECK (SoLuongTon >= 0),
    CONSTRAINT CK_SP_BH CHECK (ThoiGianBaoHanhThang >= 0),
    CONSTRAINT CK_SP_TrangThai CHECK (TrangThai IN ('ACTIVE','INACTIVE','DISCONTINUED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

/* 02. Purchasing & stock documents */
CREATE TABLE PhieuNhapKho (
    MaPhieuNhap VARCHAR(30) PRIMARY KEY,
    MaNCC VARCHAR(30) NOT NULL,
    MaNV VARCHAR(30) NOT NULL,
    NgayNhap DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TrangThai VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    GhiChu VARCHAR(500) NULL,
    CONSTRAINT FK_PNK_NCC FOREIGN KEY(MaNCC) REFERENCES NhaCungCap(MaNCC),
    CONSTRAINT FK_PNK_NV FOREIGN KEY(MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT CK_PNK_TrangThai CHECK (TrangThai IN ('DRAFT','CONFIRMED','CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ChiTietPhieuNhapKho (
    MaPhieuNhap VARCHAR(30) NOT NULL,
    MaSP VARCHAR(30) NOT NULL,
    SoLuong INT NOT NULL,
    DonGiaNhap DECIMAL(18,2) NOT NULL,
    ThanhTien DECIMAL(18,2) GENERATED ALWAYS AS (SoLuong * DonGiaNhap) STORED,
    PRIMARY KEY(MaPhieuNhap,MaSP),
    CONSTRAINT FK_CTPNK_PNK FOREIGN KEY(MaPhieuNhap) REFERENCES PhieuNhapKho(MaPhieuNhap),
    CONSTRAINT FK_CTPNK_SP FOREIGN KEY(MaSP) REFERENCES SanPham(MaSP),
    CONSTRAINT CK_CTPNK_SL CHECK (SoLuong > 0),
    CONSTRAINT CK_CTPNK_DonGia CHECK (DonGiaNhap >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

